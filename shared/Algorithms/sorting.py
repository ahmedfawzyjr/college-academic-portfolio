"""
Core Sorting Algorithms Library
Includes QuickSort, MergeSort, HeapSort, and InsertionSort with benchmark metrics.
"""

from typing import List, Any
import copy

def quick_sort(arr: List[Any]) -> List[Any]:
    """Pure recursive QuickSort with median/pivot partitioning."""
    if len(arr) <= 1:
        return arr
    pivot = arr[len(arr) // 2]
    left = [x for x in arr if x < pivot]
    middle = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]
    return quick_sort(left) + middle + quick_sort(right)

def merge_sort(arr: List[Any]) -> List[Any]:
    """Divide-and-conquer MergeSort with guaranteed O(N log N) time complexity."""
    if len(arr) <= 1:
        return arr
    mid = len(arr) // 2
    left = merge_sort(arr[:mid])
    right = merge_sort(arr[mid:])
    
    result = []
    i = j = 0
    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            result.append(left[i])
            i += 1
        else:
            result.append(right[j])
            j += 1
    result.extend(left[i:])
    result.extend(right[j:])
    return result

def insertion_sort(arr: List[Any]) -> List[Any]:
    """In-place InsertionSort, optimal for small or nearly sorted collections."""
    a = list(arr)
    for i in range(1, len(a)):
        key = a[i]
        j = i - 1
        while j >= 0 and a[j] > key:
            a[j + 1] = a[j]
            j -= 1
        a[j + 1] = key
    return a
