def demonstrate_ma301():
    print("Executing demonstration for MA301 - Operations Research...")
    data = [10, 20, 30, 40, 50]
    total = sum(data)
    average = total / len(data)
    print(f"Dataset: {data}")
    print(f"Calculated Total: {total}, Average: {average}")
    return True

if __name__ == "__main__":
    demonstrate_ma301()
