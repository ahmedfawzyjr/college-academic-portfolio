def demonstrate_cs201():
    print("Executing demonstration for CS201 - Discrete Structures...")
    data = [10, 20, 30, 40, 50]
    total = sum(data)
    average = total / len(data)
    print(f"Dataset: {data}")
    print(f"Calculated Total: {total}, Average: {average}")
    return True

if __name__ == "__main__":
    demonstrate_cs201()
